  private void renderResults() {
    if (editing || results == null || state == null) return;
    results.removeAllViews();
    List<Entry> matches = Entry.filter(state.entries, query, tagFilter, newestFirst);
    resultCount.setText(
        matches.size()
            + " observation"
            + (matches.size() == 1 ? "" : "s")
            + (state.entries.size() != matches.size()
                ? " · " + state.entries.size() + " total"
                : "")
            + " · On this device");
    if (matches.isEmpty()) {
      LinearLayout empty = card();
      TextView heading =
          label(state.entries.isEmpty() ? "Start with a moment" : "No matching observations", 22);
      empty.addView(heading);
      empty.addView(
          label(
              state.entries.isEmpty()
                  ? "A bird on your walk, an idea, a changing sky. Add a date, a few words and, if"
                      + " you like, a photo. Everything stays on this device until you export it."
                  : "Try another phrase, a date such as 2026-10, or choose All tags.",
              16));
      if (state.entries.isEmpty())
        empty.addView(button("Create your first observation", v -> beginEntry(null)));
      else
        empty.addView(
            button(
                "Clear search and filters",
                v -> {
                  query = "";
                  tagFilter = "";
                  showHome();
                }));
      results.addView(empty);
      return;
    }
    for (int index = 0; index < Math.min(matches.size(), visibleLimit); index++) {
      Entry e = matches.get(index);
      LinearLayout item = card();
      TextView date = label(e.date + (e.source.isEmpty() ? " · Note" : " · Photo observation"), 13);
      date.setTextColor(Theme.accent(this));
      item.addView(date);
      TextView title = label(e.title, 20);
      title.setTypeface(null, android.graphics.Typeface.BOLD);
      item.addView(title);
      if (!e.body.isEmpty()) {
        TextView body = label(e.body, 15);
        body.setMaxLines(3);
        body.setEllipsize(TextUtils.TruncateAt.END);
        item.addView(body);
      }
      if (!e.tags.isEmpty()) {
        TextView t = label(String.join("  ·  ", e.tags), 13);
        t.setTextColor(Theme.muted(this));
        item.addView(t);
      }
      item.setFocusable(true);
      item.setClickable(true);
      item.setContentDescription("Open " + e.title + ", " + e.date);
      item.setOnClickListener(v -> beginEntry(e));
      item.setForeground(getDrawable(android.R.drawable.list_selector_background));
      results.addView(item);
    }
    if (matches.size() > visibleLimit)
      results.addView(
          button(
              "Show 50 more",
              v -> {
                visibleLimit += 50;
                renderResults();
              }));
  }

