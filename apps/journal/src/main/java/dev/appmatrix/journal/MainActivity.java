  @Override
  protected void onDestroy() {
    handler.removeCallbacks(saveDraftLater);
    disposeUndo();
    if (pendingRestore != null && store != null) store.cancel(pendingRestore);
    io.shutdown();
    super.onDestroy();
  }

  private interface Job<T> {
    T run() throws Exception;
  }

  private interface Success<T> {
    void accept(T value);
  }

  private interface Failure {
    void accept(Exception error);
  }

  private <T> void work(String label, Job<T> job, Success<T> success, Failure failure) {
    if (busy) return;
    busy = true;
    ProgressDialog progress = new ProgressDialog(this);
    progress.setMessage(label + "…");
    progress.setIndeterminate(true);
    progress.setCancelable(false);
    progress.show();
    io.execute(
        () -> {
          try {
            T value = job.run();
            runOnUiThread(
                () -> {
                  busy = false;
                  if (!isDestroyed()) {
                    progress.dismiss();
                    success.accept(value);
                  }
                });
          } catch (Exception e) {
            runOnUiThread(
                () -> {
                  busy = false;
                  if (!isDestroyed()) {
                    progress.dismiss();
                    failure.accept(e);
                  }
                });
          } catch (OutOfMemoryError e) {
            runOnUiThread(
                () -> {
                  busy = false;
                  if (!isDestroyed()) {
                    progress.dismiss();
                    failure.accept(
                        new IOException(
                            "This operation needs more memory. Try a smaller photo or backup."));
                  }
                });
          }
        });
  }

