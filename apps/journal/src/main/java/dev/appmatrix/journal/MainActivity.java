  private void refreshUndo() {
    if (undoButton != null) undoButton.setEnabled(notesUndo != null && notesUndo.canUndo());
    if (redoButton != null) redoButton.setEnabled(notesUndo != null && notesUndo.canRedo());
  }

  private void disposeUndo() {
    if (notesUndo != null) {
      notesUndo.dispose();
      notesUndo = null;
    }
    undoButton = null;
    redoButton = null;
  }

  private void onEdited() {
    if (!editing || draft == null) return;
    captureFields();
    draft.dirty = true;
    if (draftStatus != null) draftStatus.setText("Unsaved changes · saving draft…");
    handler.removeCallbacks(saveDraftLater);
    handler.postDelayed(saveDraftLater, 350);
  }

  private void captureFields() {
    if (draft != null && titleInput != null) {
      draft.title = titleInput.getText().toString();
      draft.body = bodyInput.getText().toString();
      draft.tags = tagsInput.getText().toString();
    }
  }

  private boolean persistDraft(boolean report) {
    if (!editing || draft == null) return true;
    handler.removeCallbacks(saveDraftLater);
    captureFields();
    try {
      drafts.save(draft);
      if (draftStatus != null)
        draftStatus.setText(
            draft.dirty ? "Unsaved changes · draft kept locally" : "No unsaved changes");
      return true;
    } catch (IOException e) {
      if (draftStatus != null)
        draftStatus.setText("Draft could not be saved. Keep this screen open and try Save.");
      if (report) error(e);
      return false;
    }
  }

  private void changeDate() {
    LocalDate date;
    try {
      date = LocalDate.parse(draft.date);
    } catch (Exception e) {
      date = LocalDate.now();
    }
    new DatePickerDialog(
            this,
            (v, y, m, d) -> {
              draft.date = LocalDate.of(y, m + 1, d).toString();
              dateLabel.setText(draft.date);
              onEdited();
            },
            date.getYear(),
            date.getMonthValue() - 1,
            date.getDayOfMonth())
        .show();
  }

  private void saveEntry() {
    if (busy || draft == null) return;
    captureFields();
    final Entry entry;
    try {
      entry = draft.entry();
    } catch (IOException e) {
      error(e);
      return;
    }
    persistDraft(false);
    hideKeyboard();
    List<Entry> entries = new ArrayList<>(state.entries);
    entries.removeIf(e -> e.id.equals(entry.id));
    entries.add(entry);
    work(
        "Saving observation",
        () -> {
          Map<String, File> files = JournalStore.mediaMap(state);
          if (!entry.source.isEmpty()) {
            files.put(entry.source, drafts.media(entry.source));
            files.put(entry.rendered, drafts.media(entry.rendered));
          }
          return store.save(
              entries, Settings.readTheme(this), Settings.readExportQuality(this), files);
        },
        s -> {
          state = s;
          drafts.discard();
          showHome();
          toast("Observation saved");
        },
        this::error);
  }

  private void leaveEditor() {
    if (busy) return;
    captureFields();
    if (draft == null || !draft.dirty) {
      drafts.discard();
      showHome();
      return;
    }
    new AlertDialog.Builder(this)
        .setTitle("Keep this draft?")
        .setMessage("This observation has unsaved changes.")
        .setPositiveButton("Save observation", (d, w) -> saveEntry())
        .setNeutralButton(
            "Keep draft & close",
            (d, w) -> {
              if (persistDraft(true)) {
                showHome();
                checkDraftBanner();
              }
            })
        .setNegativeButton(
            "Discard changes",
            (d, w) ->
                new AlertDialog.Builder(this)
                    .setTitle("Discard unsaved changes?")
                    .setMessage("Saved observations and source photos are unchanged.")
                    .setPositiveButton(
                        "Discard",
                        (a, b) -> {
                          handler.removeCallbacks(saveDraftLater);
                          drafts.discard();
                          showHome();
                        })
                    .setNegativeButton("Keep editing", null)
                    .show())
        .show();
  }

  private void checkDraftBanner() {
    Button resume = button("Resume saved draft", v -> checkDraft());
    root.addView(resume, 2);
    // Starting a different observation must never silently overwrite this draft.
  }

  private void deleteEntry() {
    new AlertDialog.Builder(this)
        .setTitle("Delete this observation?")
        .setMessage(
            "“"
                + draft.title
                + "” and its private photo copies will be removed from the current journal. Other"
                + " observations are unchanged. A previously exported backup may still contain this"
                + " entry.")
        .setPositiveButton(
            "Delete observation",
            (dialog, w) -> {
              List<Entry> remaining = new ArrayList<>(state.entries);
              remaining.removeIf(e -> e.id.equals(draft.id));
              work(
                  "Deleting observation",
                  () ->
                      store.save(
                          remaining,
                          Settings.readTheme(this),
                          Settings.readExportQuality(this),
                          JournalStore.mediaMap(state)),
                  s -> {
                    state = s;
                    handler.removeCallbacks(saveDraftLater);
                    drafts.discard();
                    showHome();
                    toast("Observation deleted");
                  },
                  this::error);
            })
        .setNegativeButton("Cancel", null)
        .show();
  }

  private void pickPhoto() {
    if (!persistDraft(true)) return;
    Intent intent = new Intent(Intent.ACTION_OPEN_DOCUMENT);
    intent.addCategory(Intent.CATEGORY_OPENABLE);
    intent.setType("image/*");
    launch(intent, PICK_PHOTO);
  }

  private void photoTools() {
    if (draft.source.isEmpty()) {
      toast("Add a photo first");
      return;
    }
    new AlertDialog.Builder(this)
        .setTitle("Photo tools")
        .setItems(
            new String[] {
              "Adjust light & color curves",
              "Rotate clockwise",
              "Reset to imported source",
              "Export current photo",
              "Remove photo"
            },
            (d, w) -> {
              if (w == 0) {
                if (photo != null)
                  PhotoAdjustments.edit(this, photo, bitmap -> savePhotoRevision(bitmap));
              } else if (w == 1) {
                if (photo != null)
                  work(
                      "Rotating photo",
                      () -> BitmapTransforms.rotate(photo, 1),
                      this::savePhotoRevision,
                      this::error);
              } else if (w == 2)
                new AlertDialog.Builder(this)
                    .setTitle("Reset photo edits?")
                    .setMessage("The imported source will replace your current edited photo.")
                    .setPositiveButton(
                        "Reset",
                        (a, b) -> {
                          draft.rendered = draft.source;
                          draft.dirty = true;
                          persistDraft(true);
                          refreshPhoto();
                        })
                    .setNegativeButton("Cancel", null)
                    .show();
              else if (w == 3) {
                Intent i = new Intent(Intent.ACTION_CREATE_DOCUMENT);
                i.addCategory(Intent.CATEGORY_OPENABLE);
                i.setType("image/jpeg");
                i.putExtra(Intent.EXTRA_TITLE, "field-journal-" + draft.date + ".jpg");
                launch(i, EXPORT_PHOTO);
              } else
                new AlertDialog.Builder(this)
                    .setTitle("Remove this photo?")
                    .setMessage(
                        "The observation text will stay. Your gallery original is unchanged.")
                    .setPositiveButton(
                        "Remove photo",
                        (a, b) -> {
                          draft.source = "";
                          draft.rendered = "";
                          draft.dirty = true;
                          persistDraft(true);
                          refreshPhoto();
                        })
                    .setNegativeButton("Cancel", null)
                    .show();
            })
        .setNegativeButton("Cancel", null)
        .show();
  }

  private String writeDraftPhoto(Bitmap bitmap) throws IOException {
    String name = UUID.randomUUID() + ".jpg";
    File target = drafts.media(name);
    File temp = new File(target.getParentFile(), name + ".tmp");
    try (FileOutputStream output = new FileOutputStream(temp)) {
      BitmapTransforms.exportJpeg(bitmap, output, 90);
      output.getFD().sync();
    } catch (IOException | RuntimeException e) {
      temp.delete();
      throw e;
    }
    Files.move(
        temp.toPath(),
        target.toPath(),
        StandardCopyOption.ATOMIC_MOVE,
        StandardCopyOption.REPLACE_EXISTING);
    validatePhoto(target);
    return name;
  }

  private void savePhotoRevision(Bitmap bitmap) {
    work(
        "Saving photo adjustment",
        () -> writeDraftPhoto(bitmap),
        name -> {
          draft.rendered = name;
          draft.dirty = true;
          persistDraft(true);
          refreshPhoto();
          if (bitmap != photo && !bitmap.isRecycled()) bitmap.recycle();
        },
        e -> {
          if (bitmap != photo && !bitmap.isRecycled()) bitmap.recycle();
          error(e);
        });
  }

  private void refreshPhoto() {
    releasePhoto();
    if (image == null) return;
    if (draft == null || draft.rendered.isEmpty()) {
      image.setImageDrawable(null);
      image.setVisibility(View.GONE);
      runAfterPhotoOpened();
      return;
    }
    image.setVisibility(View.VISIBLE);
    work(
        "Opening photo",
        () -> MediaFiles.loadBitmap(drafts.media(draft.rendered).getAbsolutePath()),
        bitmap -> {
          photo = bitmap;
          image.setImageBitmap(bitmap);
          runAfterPhotoOpened();
        },
        e -> {
          image.setImageDrawable(null);
          error(e);
          runAfterPhotoOpened();
        });
  }

  private void runAfterPhotoOpened() {
    if (afterPhotoOpened != null) {
      Runnable next = afterPhotoOpened;
      afterPhotoOpened = null;
      next.run();
    }
  }

  private boolean resumePendingResult() {
    if (pendingResultUri == null) return false;
    int code = pendingResultCode;
    Uri uri = pendingResultUri;
    pendingResultUri = null;
    if (code == PICK_PHOTO || code == EXPORT_PHOTO) {
      try {
        DraftStore.Draft saved = drafts.load();
        if (saved == null || !saved.journalId.equals(state.journalId)) {
          error(
              new IOException(
                  "The photo picker returned after the draft was closed. Open an observation and"
                      + " choose the photo again."));
          return true;
        }
        draft = saved;
        afterPhotoOpened = () -> handleDocumentResult(code, uri);
        showEditor();
        return true;
      } catch (IOException error) {
        error(error);
        return true;
      }
    }
    handleDocumentResult(code, uri);
    return true;
  }

  private void releasePhoto() {
    if (image != null) image.setImageDrawable(null);
    if (photo != null && !photo.isRecycled()) photo.recycle();
    photo = null;
  }

