  private void previewRestore(Uri uri) {
    work(
        "Checking backup safely",
        () -> {
          try (InputStream input = getContentResolver().openInputStream(uri)) {
            if (input == null) throw new IOException("Cannot read this backup");
            return store.previewRestore(input);
          }
        },
        preview -> {
          pendingRestore = preview;
          int count = preview.state.entries.size(), photos = preview.state.photoCount();
          String current =
              state == null
                  ? "the existing journal"
                  : state.entries.size() + " currently saved observations";
          AlertDialog dialog =
              new AlertDialog.Builder(this)
                  .setTitle("Replace journal with this backup?")
                  .setMessage(
                      "Validated backup version 1\n"
                          + count
                          + " observations · "
                          + photos
                          + " with photos\nTheme: "
                          + preview.state.theme
                          + "\n\nThis replaces "
                          + current
                          + " and saved settings. Any unsaved draft is also discarded after you"
                          + " confirm. It does not merge. The prior complete save is kept privately"
                          + " for recovery. Export a backup first if you want a separate copy.")
                  .setPositiveButton(
                      "Replace journal",
                      (d, w) ->
                          work(
                              "Restoring journal",
                              () -> store.activate(preview),
                              s -> {
                                pendingRestore = null;
                                state = s;
                                loaded = true;
                                drafts.discard();
                                applyRestoredSettings(true);
                                showHome();
                                toast("Restored " + s.entries.size() + " observations");
                              },
                              e -> {
                                store.cancel(preview);
                                pendingRestore = null;
                                error(e);
                              }))
                  .setNegativeButton(
                      "Cancel",
                      (d, w) -> {
                        store.cancel(preview);
                        pendingRestore = null;
                      })
                  .create();
          dialog.setOnCancelListener(
              d -> {
                store.cancel(preview);
                pendingRestore = null;
              });
          dialog.show();
        },
        this::error);
  }

  private void saveSettings() {
    if (state == null) return;
    work(
        "Saving settings",
        () ->
            store.save(
                state.entries,
                Settings.readTheme(this),
                Settings.readExportQuality(this),
                JournalStore.mediaMap(state)),
        s -> {
          state = s;
          recreate();
        },
        this::error);
  }

  private void applyRestoredSettings(boolean report) {
    try {
      Settings.writeTheme(this, state.theme);
      Settings.writeExportQuality(this, state.quality);
      Theme.apply(this);
    } catch (RuntimeException e) {
      if (report)
        error(
            new IOException(
                "Journal restored, but appearance settings could not be applied. Reopen Settings to"
                    + " retry.",
                e));
    }
  }

  private void launch(Intent intent, int code) {
    if (busy) return;
    try {
      startActivityForResult(intent, code);
    } catch (ActivityNotFoundException e) {
      error(new IOException("No system document picker is available on this device", e));
    }
  }

  @Override
  protected void onActivityResult(int request, int result, Intent data) {
    super.onActivityResult(request, result, data);
    if (result != RESULT_OK || data == null || data.getData() == null) return;
    Uri uri = data.getData();
    if (!isDocumentUri(uri)) {
      error(
          new IOException(
              "Choose a file through a trusted system document provider. This picker returned an"
                  + " unsupported location."));
      return;
    }
    if (!loaded || ((request == PICK_PHOTO || request == EXPORT_PHOTO) && !editing)) {
      pendingResultCode = request;
      pendingResultUri = uri;
      if (loaded) resumePendingResult();
      return;
    }
    handleDocumentResult(request, uri);
  }

  static boolean isDocumentUri(Uri uri) {
    return uri != null
        && ContentResolver.SCHEME_CONTENT.equals(uri.getScheme())
        && !TextUtils.isEmpty(uri.getAuthority());
  }

  private void handleDocumentResult(int request, Uri uri) {
    if (!isDocumentUri(uri)) {
      error(new IOException("Choose a file through the Android system picker"));
      return;
    }
    if (request == PICK_PHOTO && editing && draft != null) {
      work(
          "Importing private photo copy",
          () -> {
            Bitmap bitmap = MediaFiles.readBitmap(this, uri, 2048);
            try {
              return writeDraftPhoto(bitmap);
            } finally {
              bitmap.recycle();
            }
          },
          name -> {
            draft.source = name;
            draft.rendered = name;
            draft.dirty = true;
            persistDraft(true);
            refreshPhoto();
          },
          this::error);
    } else if (request == EXPORT_BACKUP && state != null) {
      work(
          "Writing backup",
          () -> {
            try (OutputStream output = getContentResolver().openOutputStream(uri, "wt")) {
              if (output == null) throw new IOException("Cannot write to this destination");
              store.exportBackup(state, output);
            }
            return true;
          },
          ok -> toast("Backup exported. Keep it somewhere safe."),
          e ->
              error(
                  new IOException(
                      "Backup export failed. The destination may contain an incomplete file; remove"
                          + " it and try again. Your journal is unchanged.\n"
                          + message(e),
                      e)));
    } else if (request == RESTORE_BACKUP) {
      previewRestore(uri);
    } else if (request == EXPORT_PHOTO && editing && draft != null) {
      work(
          "Exporting photo",
          () -> {
            Bitmap bitmap = MediaFiles.loadBitmap(drafts.media(draft.rendered).getAbsolutePath());
            try {
              MediaFiles.copyTo(this, uri, bitmap, Settings.readExportQuality(this));
            } finally {
              bitmap.recycle();
            }
            return true;
          },
          ok -> toast("Photo exported"),
          e ->
              error(
                  new IOException(
                      "Photo export failed; the destination may contain an incomplete file. Your"
                          + " observation is unchanged.\n"
                          + message(e),
                      e)));
    }
  }

