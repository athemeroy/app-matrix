  static void validatePhoto(File file) throws IOException {
    // Every backed-up image must be a bounded, fully decodable JPEG generated by this app.
    JpegInspector.validate(file);
    BitmapFactory.Options bounds = new BitmapFactory.Options();
    bounds.inJustDecodeBounds = true;
    BitmapFactory.decodeFile(file.getAbsolutePath(), bounds);
    if (bounds.outWidth < 1
        || bounds.outHeight < 1
        || bounds.outWidth > 2048
        || bounds.outHeight > 2048) throw new IOException("Backup photo dimensions are invalid");
    Bitmap decoded = BitmapFactory.decodeFile(file.getAbsolutePath());
    if (decoded == null) throw new IOException("Backup photo is corrupt");
    decoded.recycle();
    try (RandomAccessFile input = new RandomAccessFile(file, "r")) {
      if (input.length() < 4) throw new IOException("Backup photo is truncated");
      input.seek(input.length() - 2);
      if (input.read() != 0xff || input.read() != 0xd9)
        throw new IOException("Backup photo is truncated");
    }
  }

