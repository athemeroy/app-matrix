  private void beginEntry(Entry entry) {
    if (busy) return;
    try {
      DraftStore.Draft pending = drafts.load();
      if (pending != null && !pending.journalId.equals(state.journalId)) {
        drafts.discard();
        pending = null;
      }
      final DraftStore.Draft resumable = pending;
      if (resumable != null && resumable.dirty) {
        new AlertDialog.Builder(this)
            .setTitle("You have a saved draft")
            .setMessage("Continue it, or explicitly discard it before opening another observation.")
            .setPositiveButton(
                "Resume draft",
                (d, w) -> {
                  draft = resumable;
                  showEditor();
                })
            .setNegativeButton("Keep draft", null)
            .setNeutralButton(
                "Discard draft",
                (d, w) ->
                    new AlertDialog.Builder(this)
                        .setTitle("Discard saved draft?")
                        .setMessage("This removes only the unsaved draft.")
                        .setPositiveButton(
                            "Discard",
                            (a, b) -> {
                              drafts.discard();
                              beginEntry(entry);
                            })
                        .setNegativeButton("Cancel", null)
                        .show())
            .show();
        return;
      }
    } catch (IOException e) {
      error(
          new IOException(
              "A draft needs recovery. Reopen the app to recover or explicitly discard it.", e));
      return;
    }
    hideKeyboard();
    work(
        "Preparing observation",
        () -> drafts.begin(entry, state),
        d -> {
          draft = d;
          showEditor();
        },
        this::error);
  }

  private void checkDraft() {
    try {
      DraftStore.Draft found = drafts.load();
      if (found == null) return;
      if (!found.journalId.equals(state.journalId)) {
        drafts.discard();
        toast("An earlier draft was removed after journal restoration");
        return;
      }
      if (!found.dirty) {
        drafts.discard();
        return;
      }
      new AlertDialog.Builder(this)
          .setTitle("Continue your draft?")
          .setMessage(
              (found.title.isEmpty() ? "Untitled observation" : found.title)
                  + "\n"
                  + found.date
                  + "\n\nYour unsaved changes were kept on this device.")
          .setPositiveButton(
              "Continue editing",
              (d, w) -> {
                draft = found;
                showEditor();
              })
          .setNegativeButton(
              "Discard draft",
              (d, w) ->
                  new AlertDialog.Builder(this)
                      .setTitle("Discard saved draft?")
                      .setMessage(
                          "Only this unsaved draft will be removed. Saved observations are"
                              + " unchanged.")
                      .setPositiveButton("Discard", (a, b) -> drafts.discard())
                      .setNegativeButton("Keep draft", (a, b) -> checkDraft())
                      .setOnCancelListener(a -> checkDraft())
                      .show())
          .setCancelable(false)
          .show();
    } catch (IOException e) {
      new AlertDialog.Builder(this)
          .setTitle("Draft could not be recovered")
          .setMessage(message(e) + "\nYour saved observations are unchanged.")
          .setPositiveButton("Keep draft", null)
          .setNegativeButton("Discard broken draft", (d, w) -> drafts.discard())
          .show();
    }
  }

